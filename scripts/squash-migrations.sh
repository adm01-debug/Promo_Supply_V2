#!/usr/bin/env bash
# scripts/squash-migrations.sh
#
# F-031: Migration squash tooling
#
# PURPOSE
# -------
# With 265+ individual migration files, cold-start times and history readability
# suffer. This script concatenates every migration up to (but not including)
# a configurable CUTOFF date into a single baseline file, then removes the
# originals so Supabase only needs to replay migrations newer than the cutoff.
#
# USAGE
# -----
#   bash scripts/squash-migrations.sh [--cutoff YYYYMMDD] [--dry-run] [--help]
#
# ARGUMENTS
#   --cutoff YYYYMMDD   Migrations strictly before this timestamp prefix are
#                       squashed.  Defaults to the oldest migration that is
#                       NOT part of the official schema baseline.
#   --dry-run           Print what would happen without changing any files.
#   --help              Show this message.
#
# OUTPUT
#   supabase/migrations/<CUTOFF>_squashed_baseline.sql  ← new combined file
#   The original files below the cutoff are DELETED (via git rm).
#
# SAFETY RULES
#   1. The working tree must be clean (git status) before running.
#   2. Never squash an existing *_squashed_baseline.sql file.
#   3. Always commit the squashed file and push before deploying to production.
#   4. On a Supabase managed project, run "supabase db reset" locally first.
#   5. Coordinate with every developer — they must "git pull" before running.
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MIGRATIONS_DIR="$(dirname "$SCRIPT_DIR")/supabase/migrations"

# ── Defaults ──────────────────────────────────────────────────────────────────
CUTOFF=""
DRY_RUN=false

# ── Parse args ────────────────────────────────────────────────────────────────
while [[ $# -gt 0 ]]; do
  case "$1" in
    --cutoff)
      CUTOFF="$2"; shift 2 ;;
    --dry-run)
      DRY_RUN=true; shift ;;
    --help|-h)
      grep '^#' "$0" | grep -v '#!/' | sed 's/^# \?//' ; exit 0 ;;
    *)
      echo "Unknown argument: $1" >&2; exit 1 ;;
  esac
done

# ── Validate ──────────────────────────────────────────────────────────────────
if [[ ! -d "$MIGRATIONS_DIR" ]]; then
  echo "ERROR: migrations directory not found: $MIGRATIONS_DIR" >&2
  exit 1
fi

# Require clean working tree (skip in dry-run)
if [[ "$DRY_RUN" = false ]]; then
  if ! git -C "$SCRIPT_DIR/.." diff --quiet HEAD 2>/dev/null; then
    echo "ERROR: working tree has uncommitted changes. Commit or stash first." >&2
    exit 1
  fi
fi

# Auto-detect cutoff: use the timestamp of the first file that looks like a
# Lovable UUID migration (format YYYYMMDDHHMMSS_<uuid>.sql).
if [[ -z "$CUTOFF" ]]; then
  CUTOFF=$(ls "$MIGRATIONS_DIR"/*.sql 2>/dev/null \
    | grep -oE '[0-9]{14}_[0-9a-f]{8}-' \
    | head -1 \
    | grep -oE '^[0-9]{14}' || echo "")

  if [[ -z "$CUTOFF" ]]; then
    echo "ERROR: could not auto-detect cutoff. Pass --cutoff YYYYMMDDHHMMSS" >&2
    exit 1
  fi
  echo "Auto-detected cutoff: $CUTOFF"
fi

# ── Collect files to squash ───────────────────────────────────────────────────
mapfile -t TO_SQUASH < <(
  ls "$MIGRATIONS_DIR"/*.sql 2>/dev/null \
    | sort \
    | awk -v cutoff="$CUTOFF" -F'/' '{
        n = split($NF, a, "_"); ts = substr(a[1], 1, 14)
        if (ts < cutoff) print $0
      }'
)

# Proteção: nunca squashear um baseline já gerado.
TO_SQUASH=($(printf '%s\n' "${TO_SQUASH[@]}" | grep -v 'squashed_baseline' || true))

COUNT="${#TO_SQUASH[@]}"

if [[ "$COUNT" -eq 0 ]]; then
  echo "No migrations older than cutoff $CUTOFF — nothing to squash."
  exit 0
fi

BASELINE_FILE="$MIGRATIONS_DIR/${CUTOFF}_squashed_baseline.sql"

echo "──────────────────────────────────────────────────────────────"
echo "  Migration squash plan"
echo "  Cutoff       : $CUTOFF"
echo "  Files to squash: $COUNT"
echo "  Output file  : $BASELINE_FILE"
echo "  Dry-run      : $DRY_RUN"
echo "──────────────────────────────────────────────────────────────"

if [[ "$DRY_RUN" = true ]]; then
  echo ""
  echo "Files that WOULD be squashed:"
  for f in "${TO_SQUASH[@]}"; do
    echo "  - $(basename "$f")"
  done
  echo ""
  echo "Would write: $(basename "$BASELINE_FILE")"
  echo "Dry-run complete — no files changed."
  exit 0
fi

# ── Write baseline ────────────────────────────────────────────────────────────
{
  echo "-- =============================================================="
  echo "-- SQUASHED BASELINE"
  echo "-- Generated by scripts/squash-migrations.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "-- Contains $COUNT migration files squashed up to cutoff $CUTOFF"
  echo "--"
  echo "-- DO NOT EDIT THIS FILE MANUALLY."
  echo "-- To regenerate: bash scripts/squash-migrations.sh --cutoff $CUTOFF"
  echo "-- =============================================================="
  echo ""

  for f in "${TO_SQUASH[@]}"; do
    echo "-- ── $(basename "$f") ───────────────────────────────────────────────"
    cat "$f"
    echo ""
  done
} > "$BASELINE_FILE"

echo "Written: $BASELINE_FILE ($(wc -l < "$BASELINE_FILE") lines)"

# ── Remove originals via git rm (mantém o índice consistente) ─────────────────
for f in "${TO_SQUASH[@]}"; do
  git -C "$SCRIPT_DIR/.." rm --quiet "$f"
  echo "  Removed: $(basename "$f")"
done

echo ""
echo "Done. $COUNT files squashed into $(basename "$BASELINE_FILE")."
echo ""
echo "NEXT STEPS:"
echo "  1. git add supabase/migrations/"
echo "  2. git commit -m 'chore: squash $COUNT migrations into baseline $CUTOFF'"
echo "  3. Run 'supabase db reset' locally to verify the schema is identical."
echo "  4. Inform all developers to 'git pull' before creating new migrations."
