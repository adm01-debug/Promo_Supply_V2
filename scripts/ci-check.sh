#!/usr/bin/env bash
set -euo pipefail

# Cross-platform: macOS, Linux, WSL, and Windows (Git Bash / MSYS / Cygwin).
# Must be invoked through bash (not cmd.exe). On Windows use Git Bash, WSL,
# or `bun run ci:check`.
source "$(dirname "$0")/lib/preflight.sh"
preflight

# ci-logs/ is generated for CI artifact upload (see .github/workflows/ci-check.yml).
# Safe to delete locally; not intended to be committed.
LOG_DIR="ci-logs"
mkdir -p "$LOG_DIR"

echo "▶ [1/14] Removing node_modules..."
rm -rf node_modules

echo "▶ [2/14] Evicting any cached date-fns tarballs..."
evict_datefns_cache

echo "▶ [3/14] Installing from frozen lockfile..."
bun install --frozen-lockfile

echo "▶ [4/14] Confirming installed date-fns version matches lockfile..."
INSTALLED="$(node -p "require('./node_modules/date-fns/package.json').version")"
LOCKED="$(resolve_locked_datefns)"
if [ -n "$LOCKED" ] && [ "$INSTALLED" != "$LOCKED" ]; then
  echo "✗ date-fns drift: installed=$INSTALLED, locked=$LOCKED" >&2
  exit 1
fi
echo "✓ date-fns $INSTALLED matches lockfile."

echo "▶ [5/14] Printing install verification report..."
node scripts/install-report.mjs 2>&1 | tee "$LOG_DIR/install-report.txt"

echo "▶ [6/15] ESLint gate (full project, --max-warnings=0): blocks date-fns barrel imports + all warnings..."
bunx eslint . --max-warnings=0 2>&1 | tee "$LOG_DIR/eslint-full.log"
ESLINT_FULL_EXIT=${PIPESTATUS[0]}
if [ "$ESLINT_FULL_EXIT" -ne 0 ]; then
  echo "✗ ESLint failed. See $LOG_DIR/eslint-full.log (uploaded as CI artifact)." >&2
  echo "  Common cause: \`import { ... } from \"date-fns\"\` (barrel) — must be \`date-fns/<subpath>\`." >&2
  exit "$ESLINT_FULL_EXIT"
fi
echo "✓ ESLint clean (zero warnings, zero barrel imports)."

echo "▶ [7/15] ESLint gate: dedicated date-fns config (defense in depth, --max-warnings=0)..."
bunx eslint . --config eslint.date-fns.config.js --max-warnings=0

echo "▶ [8/15] Verifying date-fns subpath files exist on disk..."
if ! node scripts/verify-datefns-files.mjs; then
  echo "✗ verify-datefns-files.mjs failed — broken install or missing subpath." >&2
  exit 1
fi

echo "▶ [9/15] Type-checking source with tsc --noEmit..."
bunx tsc --noEmit -p tsconfig.app.json

echo "▶ [10/15] Verifying date-fns locale imports match manifest..."
node scripts/verify-datefns-locales.mjs

echo "▶ [11/15] Verifying date-fns smoke test is up to date..."
if ! node scripts/generate-datefns-smoke-test.mjs --dry-run; then
  echo "✗ Smoke test or manifest is out of date." >&2
  echo "  Run \`node scripts/generate-datefns-smoke-test.mjs\` and commit the result." >&2
  exit 1
fi
echo "✓ Smoke test file and manifest are up to date."

echo "▶ [12/15] Validating smoke test imports against tsconfig.smoke.json (focused tsc)..."
bunx tsc --noEmit -p tsconfig.smoke.json 2>&1 | tee "$LOG_DIR/tsc-smoke.log"
SMOKE_TSC_EXIT=${PIPESTATUS[0]}
if [ "$SMOKE_TSC_EXIT" -ne 0 ]; then
  echo "✗ Focused tsc failed. See $LOG_DIR/tsc-smoke.log (uploaded as CI artifact)." >&2
  exit "$SMOKE_TSC_EXIT"
fi
echo "✓ Smoke test imports type-check cleanly."

echo "▶ [13/15] Type-checking full project with tsc --noEmit..."
bunx tsc --noEmit -p tsconfig.app.json 2>&1 | tee "$LOG_DIR/tsc-project.log"
TSC_EXIT=${PIPESTATUS[0]}
if [ "$TSC_EXIT" -ne 0 ]; then
  echo "✗ Project tsc failed. See $LOG_DIR/tsc-project.log (uploaded as CI artifact)." >&2
  exit "$TSC_EXIT"
fi

echo "▶ [14/15] Running date-fns smoke test..."
SMOKE_TEST_FILE="src/test/dateFns.smoke.test.ts"
if [ ! -f "$SMOKE_TEST_FILE" ]; then
  echo "✗ Smoke test file missing: $SMOKE_TEST_FILE" >&2
  echo "  Expected to be generated by step [11/15] (scripts/generate-datefns-smoke-test.mjs)." >&2
  echo "  Run \`node scripts/generate-datefns-smoke-test.mjs\` manually to debug." >&2
  exit 1
fi
echo "✓ Smoke test file present: $SMOKE_TEST_FILE"
bun run test:date-fns 2>&1 | tee "$LOG_DIR/vitest-smoke.log"
VITEST_EXIT=${PIPESTATUS[0]}
if [ "$VITEST_EXIT" -ne 0 ]; then
  echo "✗ Smoke vitest failed. See $LOG_DIR/vitest-smoke.log (uploaded as CI artifact)." >&2
  exit "$VITEST_EXIT"
fi

echo "▶ [15/15] Refreshing public/dependency-health.json snapshot (with diff vs. previous)..."
bun run deps:health

echo "▶ Emitting dependency-health snapshot for smoke run..."
node scripts/emit-smoke-health.mjs \
  --tsc-exit "${SMOKE_TSC_EXIT:-0}" \
  --vitest-exit "${VITEST_EXIT:-0}" \
  --out "$LOG_DIR/datefns-smoke-health.json" || true

echo "✅ CI check passed: clean install + cache evict + version match + ESLint gate + file verify + type-check green."
