#!/usr/bin/env bash
set -euo pipefail

# Cross-platform: macOS, Linux, WSL, and Windows (Git Bash / MSYS / Cygwin).
# Must be invoked through bash (not cmd.exe). On Windows use Git Bash, WSL,
# or `bun run ci:check`.
source "$(dirname "$0")/lib/preflight.sh"
preflight

echo "▶ [1/9] Removing node_modules..."
rm -rf node_modules

echo "▶ [2/9] Evicting any cached date-fns tarballs..."
evict_datefns_cache

echo "▶ [3/9] Installing from frozen lockfile..."
bun install --frozen-lockfile

echo "▶ [4/9] Confirming installed date-fns version matches lockfile..."
INSTALLED="$(node -p "require('./node_modules/date-fns/package.json').version")"
LOCKED="$(resolve_locked_datefns)"
if [ -n "$LOCKED" ] && [ "$INSTALLED" != "$LOCKED" ]; then
  echo "✗ date-fns drift: installed=$INSTALLED, locked=$LOCKED" >&2
  exit 1
fi
echo "✓ date-fns $INSTALLED matches lockfile."

echo "▶ [5/11] Printing install verification report..."
node scripts/install-report.mjs

echo "▶ [6/11] ESLint gate: blocking date-fns barrel imports (--max-warnings=0)..."
bunx eslint . --config eslint.date-fns.config.js --max-warnings=0

echo "▶ [7/11] Verifying date-fns subpath files exist on disk..."
node scripts/verify-datefns-files.mjs

echo "▶ [8/11] Type-checking source with tsc --noEmit..."
bunx tsc --noEmit -p tsconfig.app.json

echo "▶ [9/11] Verifying date-fns smoke test is up to date..."
SMOKE_TEST_FILE="src/test/dateFns.smoke.test.ts"
SMOKE_BACKUP="$(mktemp)"
if [ -f "$SMOKE_TEST_FILE" ]; then
  cp "$SMOKE_TEST_FILE" "$SMOKE_BACKUP"
fi
node scripts/generate-datefns-smoke-test.mjs
if [ -f "$SMOKE_BACKUP" ]; then
  if ! diff -q "$SMOKE_BACKUP" "$SMOKE_TEST_FILE" > /dev/null 2>&1; then
    echo "✗ $SMOKE_TEST_FILE is out of date." >&2
    echo "  Run \`node scripts/generate-datefns-smoke-test.mjs\` and commit the result." >&2
    echo "  Diff:" >&2
    diff -u "$SMOKE_BACKUP" "$SMOKE_TEST_FILE" >&2 || true
    cp "$SMOKE_BACKUP" "$SMOKE_TEST_FILE"
    rm -f "$SMOKE_BACKUP"
    exit 1
  fi
  rm -f "$SMOKE_BACKUP"
else
  echo "✗ $SMOKE_TEST_FILE did not exist before generation." >&2
  echo "  Run \`node scripts/generate-datefns-smoke-test.mjs\` and commit the result." >&2
  exit 1
fi
echo "✓ Smoke test file is up to date."

echo "▶ [10/11] Type-checking again + running date-fns smoke test..."
SMOKE_TEST_FILE="src/test/dateFns.smoke.test.ts"
if [ ! -f "$SMOKE_TEST_FILE" ]; then
  echo "✗ Smoke test file missing: $SMOKE_TEST_FILE" >&2
  echo "  Expected to be generated by step [9/11] (scripts/generate-datefns-smoke-test.mjs)." >&2
  echo "  Run \`node scripts/generate-datefns-smoke-test.mjs\` manually to debug." >&2
  exit 1
fi
echo "✓ Smoke test file present: $SMOKE_TEST_FILE"
bunx tsc --noEmit -p tsconfig.app.json
bunx vitest run "$SMOKE_TEST_FILE" --reporter=verbose --passWithNoTests

echo "▶ [11/11] Writing public/dependency-health.json snapshot via deps:health..."
bun run deps:health

echo "✅ CI check passed: clean install + cache evict + version match + file verify + type-check green."
